"""Assemble a modernized web app from a Legacy IR.

    python modern/build.py zzt <world>        e.g. zzt kingl2-kingl2
    python modern/build.py zzt all
    python modern/build.py hypercard <stack>  e.g. hypercard hypercard_obliquestrategies
    python modern/build.py hypercard all      (see modern/hypercard/build_stack.py)

Output: output/<target>/<sample>/app/
    index.html        open by double-clicking (no server, no build step)
    runtime/          shared runtime (runtime.js, render-cells.js, render-pixels.js, cp437-font.js, runtime.css)
    engine.js         the target's game layer (ZZT)
    data.js           the IR plus every board grid, as window.LEGACY_IR (no fetch: works from file://)
    scripts.js        translated object programs, as window.ZZT_PROGRAMS
    app.js            boot code
    MIGRATION.md      what was converted / stubbed, how to extend
    stats.json        counts used in reports
"""
import html
import json
import shutil
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "modern" / "zzt"))
from translator import translate_program  # noqa: E402

RUNTIME_FILES = ["runtime.js", "render-cells.js", "render-pixels.js", "cp437-font.js", "runtime.css"]


def build_zzt(world: str) -> dict:
    src = ROOT / "output" / "zzt" / world / "ir"
    app = ROOT / "output" / "zzt" / world / "app"
    ir = json.loads((src / "ir.json").read_text(encoding="utf-8"))
    if app.exists():
        shutil.rmtree(app)
    (app / "runtime").mkdir(parents=True)
    for f in RUNTIME_FILES:
        shutil.copy(ROOT / "modern" / "runtime" / f, app / "runtime" / f)
    shutil.copy(ROOT / "modern" / "zzt" / "engine.js", app / "engine.js")
    shutil.copy(ROOT / "modern" / "zzt" / "app.js", app / "app.js")

    # ---- data.js: IR + grids -------------------------------------------------------------------
    grids = {}
    for s in ir["screens"]:
        rel = s["grid"]["cells"]
        grids[rel] = json.loads((src / rel).read_text(encoding="utf-8"))
    ir_out = dict(ir, grids=grids)
    (app / "data.js").write_text(
        f"// Legacy IR for {ir['name']} ({ir['source']['file']}), generated by modern/build.py. Do not edit.\n"
        "window.LEGACY_IR = " + json.dumps(ir_out, separators=(",", ":")) + ";\n", encoding="utf-8")

    # ---- scripts.js: one module per distinct program ---------------------------------------------
    programs = {}       # text -> index
    users = defaultdict(list)
    by_object = {}
    for s in ir["screens"]:
        for o in s["objects"]:
            if not o["script"] or o["extra"]["element"] != 36:
                continue
            t = o["script"]["text"]
            if t not in programs:
                programs[t] = len(programs)
            by_object[o["id"]] = programs[t]
            users[programs[t]].append(f"{s['id']}:{o['name'] or '#' + str(o['number'])}")
    totals = Counter()
    stubs = Counter()
    stub_lines = []
    parts = [
        f"// Translated ZZT-OOP programs for {ir['name']} ({ir['source']['file']}).",
        "// Generated by modern/zzt/translator.py -- edit the translator, or copy a module into a hand-written",
        "// override (see MIGRATION.md). Each segment function = code after one :label (segment 0 = program start).",
        "// The original ZZT-OOP source is kept as // comments above each statement group.",
        "window.ZZT_PROGRAMS = (function () {",
        "'use strict';",
        "const P = [];",
        "",
    ]
    for text, idx in programs.items():
        js, st = translate_program(text, f"P[{idx}]")
        u = users[idx]
        shown = ", ".join(u[:4]) + (f", ... ({len(u)} objects)" if len(u) > 4 else "")
        parts.append(f"// ---- program {idx}: used by {shown}")
        parts.append(js)
        parts.append("")
        totals["lines"] += st.lines
        totals["translated"] += st.translated
        totals["stubbed"] += st.stubbed
        totals["handlers"] += st.segments
        totals["labels"] += st.segments - 1
        for cmd, line in st.stub_list:
            stubs[cmd] += 1
            stub_lines.append(line)
    parts.append("return { programs: P, byObject: " + json.dumps(by_object) + " };")
    parts.append("})();")
    (app / "scripts.js").write_text("\n".join(parts) + "\n", encoding="utf-8")

    # ---- index.html ------------------------------------------------------------------------------
    title = html.escape(ir["name"])
    (app / "index.html").write_text(f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="stylesheet" href="runtime/runtime.css">
</head>
<body>
<div id="app">
  <header>{title} &middot; {html.escape(ir['source']['file'])} &middot; modernized by Legacy Revive
    &middot; arrows move, Shift+arrow shoots, P plays</header>
  <div id="wrap"></div>
</div>
<script src="runtime/cp437-font.js" charset="utf-8"></script>
<script src="runtime/runtime.js" charset="utf-8"></script>
<script src="runtime/render-cells.js" charset="utf-8"></script>
<script src="runtime/render-pixels.js" charset="utf-8"></script>
<script src="data.js" charset="utf-8"></script>
<script src="scripts.js" charset="utf-8"></script>
<script src="engine.js" charset="utf-8"></script>
<script src="app.js" charset="utf-8"></script>
</body>
</html>
""", encoding="utf-8")

    n_obj = sum(1 for s in ir["screens"] for o in s["objects"] if o["extra"]["element"] == 36)
    stats = {
        "world": world, "name": ir["name"], "boards": len(ir["screens"]), "objects": n_obj,
        "scripted_objects": len(by_object), "distinct_programs": len(programs),
        "handlers": totals["handlers"], "labels": totals["labels"],
        "lines": totals["lines"], "lines_translated": totals["translated"], "lines_stubbed": totals["stubbed"],
        "stubs_by_command": dict(stubs), "stub_lines": stub_lines,
    }
    (app / "stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False), encoding="utf-8")
    (app / "MIGRATION.md").write_text(migration_md(ir, stats), encoding="utf-8")
    from zzt import postbuild  # reconstructed-behaviour notes and element coverage (iteration 2)
    postbuild.finish(world)
    return json.loads((app / "stats.json").read_text(encoding="utf-8"))


def migration_md(ir, st) -> str:
    stub_rows = "\n".join(f"| `{l}` |" for l in st["stub_lines"]) or "| (none) |"
    pct = 100 * st["lines_translated"] / st["lines"] if st["lines"] else 100
    return f"""# Migration notes: {ir['name']} ({ir['source']['file']})

Generated by `python modern/build.py zzt {st['world']}` from `output/zzt/{st['world']}/ir/` (Legacy IR v1).
Open `index.html` directly (double-click). `index.html?board=N` starts playing on board N;
`index.html?shot=1` draws only the title board at 480x350 (used by `eval/render.py`).

## What was converted

| item | count |
|---|---|
| boards (screens) | {st['boards']} |
| object records (element 36) | {st['objects']} |
| objects with a program | {st['scripted_objects']} |
| distinct programs (identical texts share one JS module) | {st['distinct_programs']} |
| handler functions (program start + one per `:label`) | {st['handlers']} |
| executable source lines | {st['lines']} |
| lines translated | {st['lines_translated']} ({pct:.2f}%) |
| lines stubbed (`z.rt.unsupported`) | {st['lines_stubbed']} |

Counts are over distinct programs. Text, `$`, `!` lines count as executable; `@name`, `'comments` and
blank lines do not.

### Files
- `data.js`: the IR and every board grid (`window.LEGACY_IR`).
- `scripts.js`: one module per distinct ZZT-OOP program. Every `:label` is an `async function on_<label>`;
  the original source is kept as `//` comments above each statement group.
- `engine.js`: the ZZT game layer (`ZztEngine`): boards, player, items, objects, bullets, sound, sidebar.
- `runtime/`: the shared Legacy Revive runtime (message hierarchy, dialogs, flags/variables, `wait`,
  `unsupported`, `?shot=1`) and the cell renderer (CP437 glyphs harvested from the reference screenshots;
  shade/box characters drawn as pixel patterns; line walls use all 16 neighbour shapes).

### Script semantics implemented
`#end #restart #send #target:label #if (flag, not, contact, alligned, blocked dir, any [color] element)
#set #clear #give #take (with failure label) #go #try /dir ?dir #walk #zap #restore (also target:label)
#become #put #change #char #cycle #lock #unlock #die #endgame #bind #shoot #throwstar #play #idle`,
text / `$` centered / `!label;choice` dialogs. Direction words `n s e w i seek flow rndns rndne opp cw
ccw rndp`. Engine-triggered labels: `touch` (player bumps the object), `shot` (player bullet hits it),
`thud` (its movement is blocked). Messages travel through `rt.send(label, objectId)`; locked objects
ignore messages from others.

## What was stubbed

| line |
|---|
{stub_rows}

Each stub calls `z.rt.unsupported(cmd, line)`, which logs once to the console and is counted in
`rt.stubReport()`.

## Known limitations (engine simplifications)
- **Creatures stand still.** Lions, tigers, bears, ruffians, sharks, slimes, centipedes, spinning guns and
  pushers do not move or attack. Touching one costs 10 health and removes it; a player bullet kills it.
- Element meanings marked G(uess) in SPEC 3.1 are engine assumptions (ammo 5, torch 6, gem 7, key 8,
  door 9, boulder 24, sliders 25/26, fake 27, invisible 28, ...). Script element words map to these numbers.
- Dark boards are drawn fully lit; torches are only a counter. Board time limits, energizers, bombs,
  duplicators, transporters, conveyors, blink walls and ricochets have no behaviour (drawn only).
- `/dir` waits up to ~50 updates for a blocked path, then gives up (ZZT presumably waits forever).
- A saved `ip` in the middle of a program restarts at the beginning of the enclosing label section.
- `#play` is an approximation (square wave; duration letters, octave +/-, sharps/flats, percussion digits
  as short blips). Sound starts after the first key press (browser autoplay rules). `S` toggles it.
- The player glyph is hidden on the title board (5 of 6 reference screenshots show it blank).
- Saving/loading games is not implemented.

## How to add a feature
- **New script command**: add a branch in `ProgramTranslator.command()` in `modern/zzt/translator.py`
  that emits a call like `z.myCommand(o, ...)`, add `myCommand(o, ...)` to `ZztEngine` in
  `modern/zzt/engine.js`, then rebuild: `python modern/build.py zzt all`.
- **Creature AI**: in `ZztEngine.tick()`, entities without a program are skipped; give elements with
  `enemy: true` an update function (e.g. move toward `this.player` with `_moveEntity`) there.
- **Change one object's behaviour by hand**: in `scripts.js` find the module (search the `@name` comment),
  edit its async functions; they only call the `z.*` API documented in `engine.js`. Rebuilding overwrites it,
  so for lasting changes add the edit to the translator or keep a patch file.
- **Another legacy program**: write a reader emitting Legacy IR, a translator for its script language, and a
  game layer on top of `runtime/runtime.js` (the HyperCard target plugs in `runtime/render-pixels.js`).
"""


def main(argv):
    if len(argv) < 3 or argv[1] not in ("zzt", "hypercard"):
        print(__doc__)
        return 2
    if argv[1] == "hypercard":
        sys.path.insert(0, str(ROOT / "modern" / "hypercard"))
        sys.modules.pop("translator", None)          # the ZZT translator has the same module name
        from build_stack import build_hypercard      # noqa: E402
        stacks = sorted(p.name for p in (ROOT / "output/hypercard").iterdir() if (p / "ir/ir.json").exists()) \
            if argv[2] == "all" else [argv[2]]
        for s in stacks:
            st = build_hypercard(s, ROOT, RUNTIME_FILES)
            print(f"{s}: cards {st['cards']}, handlers {st['handlers']}, lines {st['lines_translated']}/{st['lines']} "
                  f"translated, {st['lines_stubbed']} stubbed")
        return 0
    worlds = sorted(p.name for p in (ROOT / "output/zzt").iterdir() if (p / "ir/ir.json").exists()) \
        if argv[2] == "all" else [argv[2]]
    for w in worlds:
        st = build_zzt(w)
        print(f"{w}: boards {st['boards']}, programs {st['distinct_programs']}, handlers {st['handlers']}, "
              f"lines {st['lines_translated']}/{st['lines']} translated, {st['lines_stubbed']} stubbed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
